#!/usr/bin/env python3
# gen-sbox-rom.py - generates rtl/aes-sbox-rom.v (S-box and inverse S-box) from the AES field definition, no tables copied.

import os, sys

# This function multiplies two bytes in GF(2^8) with the AES polynomial x^8+x^4+x^3+x+1.
def gmul(a, b):
    # The running product
    p = 0
    # Eight rounds of shift and add
    for _ in range(8):
        # Add a when the low bit of b is set
        if b & 1:
            p ^= a
        # Remember the top bit of a before shifting
        hi = a & 0x80
        # Multiply a by x
        a = (a << 1) & 0xFF
        # Reduce by the AES polynomial when the top bit overflowed
        if hi:
            a ^= 0x1B
        # Move to the next bit of b
        b >>= 1
    # Return the product
    return p

# This function builds the S-box: multiplicative inverse followed by the affine transform.
def make_sbox():
    # The table to fill
    sb = [0] * 256
    # Visit every input byte
    for x in range(256):
        # Find the inverse by brute force (0 maps to 0)
        inv = 0
        # Only non-zero bytes have an inverse
        if x:
            # Search the field for y with x*y = 1
            for y in range(1, 256):
                # Stop at the first match
                if gmul(x, y) == 1:
                    inv = y
                    break
        # Apply the affine transform: b ^ rotl(b,1..4) ^ 0x63
        s = inv
        # Four rotations folded in
        for r in range(1, 5):
            s ^= ((inv << r) | (inv >> (8 - r))) & 0xFF
        # Add the constant
        sb[x] = s ^ 0x63
    # Return the finished table
    return sb

# Build both tables
SB = make_sbox()
# The inverse table is the inverse permutation of the S-box
ISB = [0] * 256
# Fill it by reversing the mapping
for i, v in enumerate(SB):
    ISB[v] = i

# Known answers from FIPS-197 guard against a wrong table
assert SB[0x00] == 0x63 and SB[0x01] == 0x7C and SB[0x53] == 0xED and SB[0xFF] == 0x16
# The inverse must undo the forward table
assert all(ISB[SB[i]] == i for i in range(256))

# Default output path is next to the RTL
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "rtl", "aes-sbox-rom.v")
# Collect the file text
lines = []
# File header comment
lines.append("// aes-sbox-rom.v - 512 x 8 ROM: addresses 0..255 hold the AES S-box, 256..511 hold the inverse S-box.")
# Generated-file note
lines.append("// This file is generated by sim/gen-sbox-rom.py from the GF(2^8) definition. Do not edit by hand.")
# Module header
lines.append("module aes_sbox_rom (")
# Clock port
lines.append("    input  wire       clk,   // Clock")
# Address port
lines.append("    input  wire [8:0] addr,  // Address: bit 8 selects the inverse table, bits 7:0 are the byte")
# Data port
lines.append("    output reg  [7:0] q      // Registered read data, valid one clock after addr")
# End of port list
lines.append(");")
# Storage array
lines.append("    // This holds the ROM contents (the tool maps it to block RAM)")
lines.append("    reg [7:0] mem [0:511];")
# Initial block header
lines.append("    // This block fills the ROM at configuration time")
lines.append("    initial begin")
# One assignment per entry
for i in range(512):
    lines.append("        mem[%d] = 8'h%02x;" % (i, SB[i] if i < 256 else ISB[i - 256]))
# Close the initial block
lines.append("    end")
# Read block header
lines.append("    // This block reads the ROM with a registered output")
lines.append("    always @(posedge clk) begin")
# Registered read
lines.append("        q <= mem[addr]; // One clock of read latency")
# Close the read block
lines.append("    end")
# End of module
lines.append("endmodule")
# Write the file
open(out, "w").write("\n".join(lines) + "\n")
# Report
print("wrote", os.path.abspath(out))

#!/usr/bin/env python3
# This script generates regtest.S, an assembly routine that checks every register x0..x31 holds its own value.
# Why generated: 30 near-identical lines per section are error-prone to type by hand.
#
# Method: fill x1..x31 with a Fibonacci-style chain (x_i = x_{i-2} + x_{i-1}, mod 2^32), so every register holds a
# different full-width 32-bit value (this matters: the upper and lower 16 bits live in different RAM blocks).
# Then re-check each link; the check overwrites a register that is no longer needed, so no scratch register is used.

# This is the first chain value (x1) and the second (x2); both are arbitrary odd constants.
X1 = 0x9E3779B1
X2 = 0x85EBCA6B
# These are the registers the C ABI says a function must preserve, except sp (kept in memory at the bottom of the stack area, address 0xB30).
SAVED = [1, 3, 4, 8, 9] + list(range(18, 28))
# This is the stack frame size in bytes (must be a multiple of 16 and hold all SAVED registers).
FRAME = 64

# This computes the expected chain values in Python (index 1..31).
v = {1: X1, 2: X2}
for i in range(3, 32):
    v[i] = (v[i - 2] + v[i - 1]) & 0xFFFFFFFF

# This holds the lines of the output assembly file.
out = []
# This appends one line of assembly.
def emit(s=""):
    out.append(s)

# File header comments.
emit("# Generated by gen-regtest.py - do not edit by hand.")
emit("# regtest(): puts a distinct value in every register, checks them all, returns 0 on pass or the register number on failure.")
emit("    .section .text")
emit("    .globl regtest")
emit("regtest:")
emit("    # Make a stack frame and save the callee-saved registers in it.")
emit(f"    addi sp, sp, -{FRAME}")
for k, r in enumerate(SAVED):
    emit(f"    sw x{r}, {4*k}(sp)")
emit("    # Park sp in memory (the word at 0xB30, the bottom of the stack area) because the test overwrites sp itself.")
emit("    li x5, 0xB30")
emit("    sw sp, 0(x5)")
emit("    # Fill the chain: x1 and x2 are constants, every other register is the sum of the two before it.")
emit(f"    li x1, 0x{X1:08X}")
emit(f"    li x2, 0x{X2:08X}")
for i in range(3, 32):
    emit(f"    add x{i}, x{i-2}, x{i-1}")
emit("    # x0 must stay zero even when written.")
emit("    addi x0, x0, 5")
emit("    bnez x0, fail_x0")
emit("    # Check each link: rebuild x_i from the registers before it (overwriting x_{i-2}, which is no longer needed).")
for i in range(3, 32):
    emit(f"    add x{i-2}, x{i-2}, x{i-1}")
    emit(f"    bne x{i}, x{i-2}, fail_x{i}")
emit("    # Absolute checks on the last two registers (x28 and x29 are free now), anchoring the whole chain.")
emit(f"    li x28, 0x{v[30]:08X}")
emit("    bne x30, x28, fail_x30")
emit(f"    li x29, 0x{v[31]:08X}")
emit("    bne x31, x29, fail_x31")
emit("    # Everything matched: result 0.")
emit("    li a0, 0")
emit("    j restore")

# This emits the shared failure landing pads, one per register.
emit("    # Failure landing pads: load the failing register number into a0 and leave.")
emit("fail_x0:")
emit("    li a0, 32")
emit("    j restore")
for i in range(1, 32):
    emit(f"fail_x{i}:")
    emit(f"    li a0, {i}")
    emit("    j restore")

# This emits the common exit: restore sp from memory, reload the saved registers and return.
emit("restore:")
emit("    # Bring sp back from memory, then reload the callee-saved registers.")
emit("    li sp, 0xB30")
emit("    lw sp, 0(sp)")
for k, r in enumerate(SAVED):
    emit(f"    lw x{r}, {4*k}(sp)")
emit(f"    addi sp, sp, {FRAME}")
emit("    ret")

# Write the file next to this script.
open("regtest.S", "w").write("\n".join(out) + "\n")
print("wrote regtest.S")

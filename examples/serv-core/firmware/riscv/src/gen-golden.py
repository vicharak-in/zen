#!/usr/bin/env python3
# Computes the expected (golden) results for selftest.c on the host and writes golden.h
# The firmware recomputes the same checksums on the SERV core; a mismatch means the core (or the SoC) is wrong, not the C compiler,
# because the expected numbers come from this independent Python model of RV32I.
import sys

M = 0xFFFFFFFF

# Converts an unsigned 32-bit value to a signed Python int
def s32(x):
    # Values with bit 31 set are negative
    return x - (1 << 32) if x & 0x80000000 else x

# xorshift32 generator, identical to the one in selftest.c
def xorshift(x):
    # Three shift-xor steps, all masked to 32 bits
    x ^= (x << 13) & M
    x ^= x >> 17
    x ^= (x << 5) & M
    return x & M

# Folds one result into a checksum: rotate left by 1 then xor, same as the C code
def fold(c, r):
    # Rotate left one bit, then xor in the new result
    return (((c << 1) | (c >> 31)) & M) ^ (r & M)

# Edge-case operand pairs tested first (same list as selftest.c)
EDGE = [(0, 0), (1, 1), (M, 1), (0x7FFFFFFF, 1), (0x80000000, M), (0x80000000, 0x7FFFFFFF), (5, M - 4), (0x12345678, 0x9ABCDEF0)]
# Number of pseudo-random pairs after the edge cases
NRAND = 56
# Seed for the generator
SEED = 0x2545F491

# Builds the full list of operand pairs
def pairs():
    # Start with the edge cases
    out = list(EDGE)
    # Generator state
    x = SEED
    # Append random pairs
    for _ in range(NRAND):
        # First operand
        x = xorshift(x); a = x
        # Second operand
        x = xorshift(x); b = x
        out.append((a, b))
    return out

# The 19 ALU operations: register-register then register-immediate forms
OPS = [
    ("add",   lambda a, b: (a + b) & M),
    ("sub",   lambda a, b: (a - b) & M),
    ("and",   lambda a, b: a & b),
    ("or",    lambda a, b: a | b),
    ("xor",   lambda a, b: a ^ b),
    ("slt",   lambda a, b: 1 if s32(a) < s32(b) else 0),
    ("sltu",  lambda a, b: 1 if a < b else 0),
    ("sll",   lambda a, b: (a << (b & 31)) & M),
    ("srl",   lambda a, b: a >> (b & 31)),
    ("sra",   lambda a, b: (s32(a) >> (b & 31)) & M),
    ("addi",  lambda a, b: (a - 1234) & M),
    ("xori",  lambda a, b: a ^ 0x555),
    ("andi",  lambda a, b: a & 0xFFFFFF00),
    ("ori",   lambda a, b: a | 0x7FF),
    ("slti",  lambda a, b: 1 if s32(a) < -7 else 0),
    ("sltiu", lambda a, b: 1 if a < ((-7) & M) else 0),
    ("slli",  lambda a, b: (a << 3) & M),
    ("srli",  lambda a, b: a >> 9),
    ("srai",  lambda a, b: (s32(a) >> 31) & M),
]

# Branch test pairs (same list as selftest.c)
BR_PAIRS = [(0, 0), (1, 2), (2, 1), (M, 1), (1, M), (0x80000000, 0x7FFFFFFF), (0x7FFFFFFF, 0x80000000)]
# The six branch conditions
BR_OPS = [
    ("beq",  lambda a, b: a == b),
    ("bne",  lambda a, b: a != b),
    ("blt",  lambda a, b: s32(a) < s32(b)),
    ("bge",  lambda a, b: s32(a) >= s32(b)),
    ("bltu", lambda a, b: a < b),
    ("bgeu", lambda a, b: a >= b),
]

# Software multiply/divide checks: 16 pairs, divisor forced non-zero
def softmath():
    # Checksums for multiply low word, unsigned divide, unsigned remainder
    cm = cd = cr = 0
    # Generator state, different seed from the ALU test
    x = 0x1B873593
    # 16 operand pairs
    for _ in range(16):
        x = xorshift(x); a = x
        x = xorshift(x); b = (x >> 12) | 1   # keep the divisor smaller so quotients are interesting, and never zero
        cm = fold(cm, (a * b) & M)
        cd = fold(cd, a // b)
        cr = fold(cr, a % b)
    return cm, cd, cr

# Writes golden.h
def main():
    # Output file name
    out = sys.argv[1] if len(sys.argv) > 1 else "golden.h"
    # Per-op checksums
    sums = []
    for name, f in OPS:
        c = 0
        for a, b in pairs():
            c = fold(c, f(a, b))
        sums.append(c)
    # Branch masks: bit i set when the branch is taken for pair i
    masks = []
    for name, f in BR_OPS:
        m = 0
        for i, (a, b) in enumerate(BR_PAIRS):
            if f(a, b): m |= 1 << i
        masks.append(m)
    # Soft math checksums
    cm, cd, cr = softmath()
    with open(out, "w") as h:
        h.write("/* Generated by gen-golden.py - do not edit. Expected results computed by an independent Python RV32I model. */\n")
        h.write("#define N_ALU_OPS %d\n" % len(OPS))
        h.write("#define N_EDGE %d\n#define N_RAND %d\n#define SEED_ALU 0x%08XU\n" % (len(EDGE), NRAND, SEED))
        h.write("/* ALU op index order: %s */\n" % " ".join(n for n, _ in OPS))
        h.write("static const unsigned alu_golden[N_ALU_OPS] = {%s};\n" % ", ".join("0x%08XU" % s for s in sums))
        h.write("static const unsigned br_golden[6] = {%s};\n" % ", ".join("0x%02XU" % m for m in masks))
        h.write("#define SOFT_MUL 0x%08XU\n#define SOFT_DIV 0x%08XU\n#define SOFT_REM 0x%08XU\n" % (cm, cd, cr))
    print("wrote", out)

main()
